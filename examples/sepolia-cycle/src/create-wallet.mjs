/**
 * Create a fresh Sepolia test wallet. Prints ONLY public addresses.
 * Writes secrets to examples/sepolia-cycle/.env (gitignored).
 *
 * Critical stop: do not shield or send txs until the human funds + approves.
 */
import fs from 'node:fs';
import path from 'node:path';
import { Mnemonic, randomBytes, Wallet, HDNodeWallet } from 'ethers';
import { createRailgunWallet, loadWalletByID } from '@railgun-community/wallet';
import {
  DEPLOYMENT_BLOCK,
  NETWORK,
  ROOT_DIR,
  SEPOLIA_RPC_URL,
} from './constants.mjs';
import { startEngine, stopEngine } from './engine.mjs';

const ENV_PATH = path.join(ROOT_DIR, '.env');

function writeEnv(values) {
  const lines = [
    `# Generated by create-wallet.mjs — testnet only. Never commit.`,
    `SEPOLIA_RPC_URL=${values.SEPOLIA_RPC_URL}`,
    `MNEMONIC=${values.MNEMONIC}`,
    `ENCRYPTION_KEY=${values.ENCRYPTION_KEY}`,
    `RAILGUN_WALLET_ID=${values.RAILGUN_WALLET_ID}`,
    `PUBLIC_ADDRESS=${values.PUBLIC_ADDRESS}`,
    `RAILGUN_ADDRESS=${values.RAILGUN_ADDRESS}`,
    '',
  ];
  fs.writeFileSync(ENV_PATH, lines.join('\n'), { mode: 0o600 });
}

async function main() {
  if (fs.existsSync(ENV_PATH)) {
    const existing = fs.readFileSync(ENV_PATH, 'utf8');
    if (/MNEMONIC=.+/.test(existing) && !process.argv.includes('--force')) {
      console.error(
        '.env already exists. Pass --force to overwrite, or run npm run show-address.',
      );
      process.exit(1);
    }
  }

  console.log('Starting RAILGUN engine (Sepolia)…');
  await startEngine({ debug: false });

  const mnemonic = Mnemonic.fromEntropy(randomBytes(16)).phrase.trim();
  const encryptionKey =
    Buffer.from(randomBytes(32)).toString('hex');

  const creationBlockMap = {
    [NETWORK]: DEPLOYMENT_BLOCK,
  };

  const created = await createRailgunWallet(
    encryptionKey,
    mnemonic,
    creationBlockMap,
  );

  const walletInfo = await loadWalletByID(encryptionKey, created.id, false);

  const publicWallet = HDNodeWallet.fromPhrase(mnemonic);
  const publicAddress = publicWallet.address;
  const railgunAddress = walletInfo.railgunAddress;

  writeEnv({
    SEPOLIA_RPC_URL,
    MNEMONIC: mnemonic,
    ENCRYPTION_KEY: encryptionKey,
    RAILGUN_WALLET_ID: walletInfo.id,
    PUBLIC_ADDRESS: publicAddress,
    RAILGUN_ADDRESS: railgunAddress,
  });

  // Sanity: derive address matches
  const check = Wallet.fromPhrase(mnemonic);
  if (check.address.toLowerCase() !== publicAddress.toLowerCase()) {
    throw new Error('Public address mismatch');
  }

  console.log('');
  console.log('=== TEST WALLET CREATED (Sepolia only) ===');
  console.log(`Public 0x:  ${publicAddress}`);
  console.log(`RAILGUN 0zk: ${railgunAddress}`);
  console.log('');
  console.log('Secrets written to examples/sepolia-cycle/.env (gitignored).');
  console.log('STOP: fund this 0x on Sepolia, then approve before any txs.');

  await stopEngine();
}

main().catch(async (err) => {
  console.error(err);
  await stopEngine();
  process.exit(1);
});
