import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

function pkgVersion(name) {
  try {
    return require(`${name}/package.json`).version;
  } catch {
    try {
      const lock = JSON.parse(
        fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'),
      );
      return lock.packages?.[`node_modules/${name}`]?.version ?? 'unknown';
    } catch {
      return 'unknown';
    }
  }
}

export async function writeResultMarkdown(result) {
  const versions = {
    '@railgun-community/wallet': pkgVersion('@railgun-community/wallet'),
    '@railgun-community/shared-models': pkgVersion(
      '@railgun-community/shared-models',
    ),
    ethers: pkgVersion('ethers'),
    snarkjs: pkgVersion('snarkjs'),
    leveldown: pkgVersion('leveldown'),
  };

  const step = (name) => result.steps?.[name] ?? { status: 'not-run' };
  const line = (s) => {
    if (s.status === 'pass') {
      const extras = [];
      if (s.txHash) extras.push(`tx \`${s.txHash}\``);
      if (s.etherscan) extras.push(`[etherscan](${s.etherscan})`);
      if (s.proofTimeSec != null) extras.push(`proof ${s.proofTimeSec}s`);
      if (s.shieldedWethSpendable) {
        extras.push(`spendable ${s.shieldedWethSpendable} WETH`);
      } else if (s.shieldedWeth) {
        extras.push(`balance ${s.shieldedWeth} WETH`);
      }
      if (s.shieldedWethTotal) extras.push(`total ${s.shieldedWethTotal} WETH`);
      if (s.ppoi != null) {
        extras.push(
          `PPOI: ${typeof s.ppoi === 'string' ? s.ppoi : 'see raw below'}`,
        );
      }
      if (s.amountEth) extras.push(`amount ${s.amountEth} ETH`);
      return `**pass**${extras.length ? ` — ${extras.join('; ')}` : ''}`;
    }
    if (s.status === 'fail') {
      return `**fail** — \`${(s.error ?? 'unknown').replace(/`/g, "'")}\``;
    }
    return `**${s.status}**`;
  };

  const md = `# Sepolia cycle RESULT

Generated by \`examples/sepolia-cycle\`. Testnet only.

## Overall

**${result.overall ?? 'incomplete'}**

## Versions

| Package | Version |
|---------|---------|
| @railgun-community/wallet | ${versions['@railgun-community/wallet']} |
| @railgun-community/shared-models | ${versions['@railgun-community/shared-models']} |
| ethers | ${versions.ethers} |
| snarkjs | ${versions.snarkjs} |
| leveldown | ${versions.leveldown} |

Pinned in package.json: wallet@10.4.0, shared-models@7.6.1, ethers@6.13.1 (official docs stable set).

## Network

- Network: \`${result.network ?? 'Ethereum_Sepolia'}\`
- Proxy: \`${result.proxy ?? ''}\`
- Deployment block: \`${result.deploymentBlock ?? ''}\`
- WETH: \`${result.weth ?? ''}\`

## Steps

| Step | Result |
|------|--------|
| Shield | ${line(step('shield'))} |
| Scan | ${line(step('scan'))} |
| Unshield proof | ${line(step('unshieldProof'))} |
| Unshield submit | ${line(step('unshieldSubmit'))} |

## PPOI

${step('scan').ppoi != null ? String(typeof step('scan').ppoi === 'string' ? step('scan').ppoi : JSON.stringify(step('scan').ppoi, null, 2)) : '_Not recorded yet._'}

## Issue #120

https://github.com/Railgun-Community/wallet/issues/120

**Appeared?** ${result.issue120 == null ? '_unknown / not reached_' : result.issue120 === false ? '**no**' : String(result.issue120)}

## Raw

\`\`\`json
${JSON.stringify({ ...result, versions }, null, 2)}
\`\`\`
`;

  const out = path.join(root, 'RESULT.md');
  fs.writeFileSync(out, md);
  console.log('Wrote', out);
}
